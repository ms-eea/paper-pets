export const DAILY_REWARD_LADDER = [15, 25, 35, 45, 60, 75, 100] as const;

export function getDailyRewardForStreak(streakDay: number): number {
  const safeDay = Math.max(1, Math.floor(streakDay));
  const indexInWeek = (safeDay - 1) % 7;
  const completedWeeks = Math.floor((safeDay - 1) / 7);
  const weekBonus = Math.min(50, completedWeeks * 25);
  return DAILY_REWARD_LADDER[indexInWeek] + weekBonus;
}

export function getLocalDateKey(date: Date = new Date()): string {
  const y = date.getFullYear();
  const m = String(date.getMonth() + 1).padStart(2, '0');
  const d = String(date.getDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

export function getPreviousDateKey(dateKey: string): string {
  const [y, m, d] = dateKey.split('-').map(Number);
  const prev = new Date(y, (m || 1) - 1, (d || 1) - 1);
  return getLocalDateKey(prev);
}

